"""
nose_blink_app.py

Description:
    Main interactive application for the LED canvas. 
    Combines 3D head pose tracking (nose pointing), facial blendshapes (mouth scaling), 
    and blink detection to drive a 2D physics-based "Black Hole" UI.

Features:
    - Moving Average Smoothing (Queue-based low-pass filter)
    - Blink-Freezing (Stops matrix jitter during eye closure)
    - Dynamic Mouth Scaling (Event horizon radius tied to jaw openness)
    - 2D Custom Particle Physics Engine

Dependencies:
    Requires 'nose_config.json' generated by nose_calibration.py.
    Includes Subsurface mapping (OFFSET_X, OFFSET_Y) to map purely to the physical LED wall.
"""


import os
import cv2
import json
import math
import random
import numpy as np
import pygame
import urllib.request
import collections
import mediapipe as mp
from mediapipe.tasks import python
from mediapipe.tasks.python import vision

print("🚀 Starting Black Hole Physics Sandbox...")

# --- BULLETPROOF PATH RESOLUTION ---
# Finds the current script's directory, then goes UP two levels to the root
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, '..', '..'))

LED_CONFIG_PATH = os.path.join(ROOT_DIR, "led_config.json")
NOSE_CONFIG_PATH = os.path.join(ROOT_DIR, "nose_config.json")
# Assuming we move the task file to a 'models' folder at the root
MODEL_PATH = os.path.join(ROOT_DIR, "models", "face_landmarker.task") 

# 1. Load Configurations
try:
    with open(LED_CONFIG_PATH, "r") as f:
        led_cfg = json.load(f)
    CANVAS_W = int(led_cfg.get("width", 256))
    CANVAS_H = int(led_cfg.get("height", 256))
    OFFSET_X = int(led_cfg.get("offset_x", 0))
    OFFSET_Y = int(led_cfg.get("offset_y", 0))
except Exception:
    print(f"⚠️ Could not find {LED_CONFIG_PATH}, using defaults.")
    CANVAS_W, CANVAS_H, OFFSET_X, OFFSET_Y = 256, 256, 0, 0

try:
    with open(NOSE_CONFIG_PATH, "r") as f:
        matrix = np.array(json.load(f)["homography_matrix"], dtype=np.float32)
except Exception:
    print(f"❌ Run nose_calibration.py first! Could not find: {NOSE_CONFIG_PATH}")
    exit()

# 2. Setup MediaPipe
options = vision.FaceLandmarkerOptions(
    base_options=python.BaseOptions(model_asset_path=MODEL_PATH),
    num_faces=1,
    output_face_blendshapes=True,
    output_facial_transformation_matrixes=True,
    running_mode=vision.RunningMode.IMAGE
)
detector = vision.FaceLandmarker.create_from_options(options)

# ... (rest of Pygame setup and main loop remains identical)

cap = cv2.VideoCapture(0)
pygame.init()
OS_W, OS_H = 1920, 1080
try:
    screen = pygame.display.set_mode((OS_W, OS_H), pygame.FULLSCREEN, display=1)
except Exception:
    screen = pygame.display.set_mode((OS_W, OS_H), pygame.FULLSCREEN)
pygame.mouse.set_visible(False)

# Create the virtual LED canvas
canvas = pygame.Surface((CANVAS_W, CANVAS_H))

# --- STATE VARIABLES ---
shapes = []
is_blinking = False
blink_threshold = 0.5 

HISTORY_SIZE = 8
history_x = collections.deque([CANVAS_W // 2]*HISTORY_SIZE, maxlen=HISTORY_SIZE)
history_y = collections.deque([CANVAS_H // 2]*HISTORY_SIZE, maxlen=HISTORY_SIZE)

smooth_radius = 0.5
reticle_particles = [] 

running = True
while running:
    success, frame = cap.read()
    if not success: continue

    results = detector.detect(mp.Image(image_format=mp.ImageFormat.SRGB, data=cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)))
    current_time_ms = pygame.time.get_ticks()
    current_blink_score = 0.0

    if results.facial_transformation_matrixes and results.face_blendshapes:
        bs = {cat.category_name: cat.score for cat in results.face_blendshapes[0]}
        current_blink_score = (bs.get('eyeBlinkLeft', 0) + bs.get('eyeBlinkRight', 0)) / 2.0
        
        # --- MOUTH SCALING ---
        jaw_open = bs.get('jawOpen', 0.0)
        jaw_deadzone = 0.04
        if jaw_open <= jaw_deadzone:
            target_radius = 0.5
        else:
            active_jaw = jaw_open - jaw_deadzone
            target_radius = min(40.0, 0.5 + (active_jaw * 60.0))

        smooth_radius = (0.3 * target_radius) + (0.7 * smooth_radius)

        # --- 3D HEAD MATRIX ---
        transform_matrix = results.facial_transformation_matrixes[0]
        R = transform_matrix[:3, :3] 
        head_yaw = math.degrees(math.atan2(-R[2, 0], math.sqrt(R[0, 0]**2 + R[1, 0]**2)))
        head_pitch = math.degrees(math.atan2(R[2, 1], R[2, 2]))

        src_pt = np.array([[[head_yaw, head_pitch]]], dtype=np.float32)
        dst_pt = cv2.perspectiveTransform(src_pt, matrix)
        raw_x, raw_y = dst_pt[0][0][0], dst_pt[0][0][1]

        # BLINK FREEZE
        if current_blink_score < 0.2:
            history_x.append(raw_x)
            history_y.append(raw_y)

    nose_x = max(0, min(CANVAS_W, int(sum(history_x) / len(history_x))))
    nose_y = max(0, min(CANVAS_H, int(sum(history_y) / len(history_y))))

    # --- BLINK LOGIC ---
    if current_blink_score > blink_threshold and not is_blinking:
        is_blinking = True
        
        shape_particles = []
        for _ in range(16):
            angle = random.uniform(0, 2 * math.pi)
            dist = smooth_radius + random.uniform(2, 6)
            ox, oy = math.cos(angle) * dist, math.sin(angle) * dist
            
            speed = random.uniform(1.5, 3.5)
            vx = -math.sin(angle) * speed + random.uniform(-0.5, 0.5)
            vy = math.cos(angle) * speed + random.uniform(-0.5, 0.5)
            shape_particles.append([ox, oy, vx, vy])

        shapes.append({
            "x": nose_x, "y": nose_y, 
            "color": (255, 50, 150), 
            "radius": smooth_radius, 
            "created_at": current_time_ms,
            "particles": shape_particles
        })
    elif current_blink_score < (blink_threshold - 0.1) and is_blinking:
        is_blinking = False

    # --- EVENT HANDLING ---
    for event in pygame.event.get():
        if event.type == pygame.QUIT or (event.type == pygame.KEYDOWN and event.key == pygame.K_ESCAPE): running = False
        elif event.type == pygame.KEYDOWN and event.key == pygame.K_x: shapes.clear()

    # --- RENDER TO VIRTUAL CANVAS ---
    canvas.fill((0, 0, 0))

    # 1. Draw Dropped Shapes and their Physics Particles
    for s in shapes:
        pulse = (math.sin((current_time_ms - s["created_at"]) * 0.004) + 1.0) / 2.0 
        intensity = 0.2 + (0.8 * pulse)
        r, g, b = int(s["color"][0]*intensity), int(s["color"][1]*intensity), int(s["color"][2]*intensity)
        
        if s["radius"] < 1.0:
            pygame.draw.rect(canvas, (r, g, b), (int(s["x"]), int(s["y"]), 1, 1))
        else:
            pygame.draw.circle(canvas, (r, g, b), (int(s["x"]), int(s["y"])), int(s["radius"]))

        for p in s["particles"]:
            ox, oy, vx, vy = p
            ox += vx
            oy += vy
            dist_to_center = math.hypot(ox, oy)
            
            if dist_to_center > 0:
                gx = -(ox / dist_to_center) * 0.15
                gy = -(oy / dist_to_center) * 0.15
                vx += gx
                vy += gy
            
            if dist_to_center < s["radius"] + 1:
                if dist_to_center == 0: dist_to_center = 1
                nx, ny = ox / dist_to_center, oy / dist_to_center
                dot = vx * nx + vy * ny
                if dot < 0:
                    vx -= 2 * dot * nx
                    vy -= 2 * dot * ny
                ox = nx * (s["radius"] + 1)
                oy = ny * (s["radius"] + 1)

            vx *= 0.98
            vy *= 0.98
            p[0], p[1], p[2], p[3] = ox, oy, vx, vy
            
            pygame.draw.rect(canvas, (50, 50, 50), (int(s["x"] + ox), int(s["y"] + oy), 1, 1))

    # 2. Draw Black Hole Reticle
    outer_radius = smooth_radius + 24
    dim_color = (0, 80, 120) if not is_blinking else (100, 100, 100)

    for i in range(36):
        a = (i / 36.0) * math.pi * 2 + (current_time_ms * 0.001)
        dx = int(nose_x + math.cos(a) * outer_radius)
        dy = int(nose_y + math.sin(a) * outer_radius)
        pygame.draw.rect(canvas, dim_color, (dx, dy, 1, 1))

    if smooth_radius > 1.0:
        for i in range(24):
            a = (i / 24.0) * math.pi * 2 - (current_time_ms * 0.001)
            dx = int(nose_x + math.cos(a) * smooth_radius)
            dy = int(nose_y + math.sin(a) * smooth_radius)
            pygame.draw.rect(canvas, dim_color, (dx, dy, 1, 1))

    pulse = (math.sin(current_time_ms * 0.008) + 1.0) / 2.0
    c_val = int(100 + 155 * pulse)
    pygame.draw.rect(canvas, (c_val, c_val, c_val), (int(nose_x), int(nose_y), 1, 1))

    for _ in range(4):
        a = random.uniform(0, 2 * math.pi)
        px = nose_x + math.cos(a) * outer_radius
        py = nose_y + math.sin(a) * outer_radius
        
        tangent = random.uniform(1.0, 2.5)
        inward = random.uniform(0.1, 0.5)
        vx = -math.sin(a) * tangent - math.cos(a) * inward
        vy = math.cos(a) * tangent - math.sin(a) * inward

        reticle_particles.append({
            "x": px, "y": py,
            "vx": vx, "vy": vy,
            "passed_inner": False
        })

    alive_particles = []
    for p in reticle_particles:
        dx = nose_x - p["x"]
        dy = nose_y - p["y"]
        dist = math.hypot(dx, dy)

        if dist > 0:
            force = 15.0 / (dist + 5.0) 
            p["vx"] += (dx / dist) * force * 0.1
            p["vy"] += (dy / dist) * force * 0.1

        p["vx"] *= 0.96
        p["vy"] *= 0.96
        p["x"] += p["vx"]
        p["y"] += p["vy"]

        if dist < smooth_radius and not p["passed_inner"]:
            p["passed_inner"] = True
            if random.random() < 0.65:
                continue 
            else:
                p["vx"] *= 0.25 
                p["vy"] *= 0.25 

        if dist < 2.0:
            continue

        p_color = (255, 255, 255) if p["passed_inner"] else (0, 160, 220)
        if is_blinking: p_color = (150, 150, 150)
        
        pygame.draw.rect(canvas, p_color, (int(p["x"]), int(p["y"]), 1, 1))
        alive_particles.append(p)

    reticle_particles = alive_particles

    # --- BLIT CANVAS TO SCREEN ---
    screen.fill((0, 0, 0)) # Ensure OS bounds are black
    screen.blit(canvas, (OFFSET_X, OFFSET_Y))
    pygame.display.flip()

cap.release()
pygame.quit()